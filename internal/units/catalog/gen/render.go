package gen

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
)

const (
	generatedHeader = "// Code generated by internal/units/catalog/gen from registry/units.toml. DO NOT EDIT.\n"

	typeStage     = "Stage"
	typeScope     = "Scope"
	typeDomain    = "Domain"
	typePrivilege = "Privilege"
)

func writef(b *bytes.Buffer, format string, args ...any) {
	b.Write(fmt.Appendf(nil, format, args...))
}

// RenderContractEnums renders internal/contract/enums_gen.go from a validated
// Catalog.
func RenderContractEnums(cat Catalog) ([]byte, error) {
	unitIDs := collectUnitIDs(cat)
	stages := collectStages(cat)
	scopes := collectScopes(cat)
	domains := collectDomains(cat)
	privileges := collectPrivileges(cat)

	var b bytes.Buffer
	b.WriteString(generatedHeader)
	b.WriteString("\npackage contract\n\n")

	writeEnum(&b, enumSpec{
		typeName: "UnitID",
		typeDoc:  "UnitID identifies a unit in the catalog.",
		constDoc: "UnitID values generated from registry/units.toml.",
		prefix:   "Unit",
		allFunc:  "AllUnitIDs",
		allDoc:   "AllUnitIDs returns a fresh slice of every valid UnitID in catalog order.",
		recv:     "u",
		values:   unitIDs,
	})

	writeEnum(&b, enumSpec{
		typeName: typeStage,
		typeDoc:  "Stage identifies an execution stage scope in the setup order.",
		constDoc: "Stage values generated from registry/units.toml.",
		prefix:   typeStage,
		allFunc:  "AllStages",
		allDoc:   "AllStages returns a fresh slice of every valid Stage in catalog order.",
		recv:     "s",
		values:   stages,
	})

	writeEnum(&b, enumSpec{
		typeName: typeScope,
		typeDoc:  "Scope identifies the execution privilege scope (root or user).",
		constDoc: "Scope values derived from registry/units.toml privileges.",
		prefix:   typeScope,
		allFunc:  "AllScopes",
		allDoc:   "AllScopes returns a fresh slice of every valid Scope.",
		recv:     "s",
		values:   scopes,
	})

	writeEnum(&b, enumSpec{
		typeName: typeDomain,
		typeDoc:  "Domain groups related units in the catalog.",
		constDoc: "Domain values generated from registry/units.toml.",
		prefix:   typeDomain,
		allFunc:  "AllDomains",
		allDoc:   "AllDomains returns a fresh slice of every valid Domain in catalog order.",
		recv:     "d",
		values:   domains,
	})

	scopeCases := make([]scopeMapping, 0, len(privileges))
	for _, p := range privileges {
		scopeCases = append(scopeCases, scopeMapping{
			privConst:  goIdent(typePrivilege, p),
			scopeConst: goIdent(typeScope, scopeForPrivilege(p)),
		})
	}
	writeEnum(&b, enumSpec{
		typeName:   typePrivilege,
		typeDoc:    "Privilege identifies the account role that executes a unit on an OS.",
		constDoc:   "Privilege values generated from registry/units.toml.",
		prefix:     typePrivilege,
		allFunc:    "AllPrivileges",
		allDoc:     "AllPrivileges returns a fresh slice of every valid Privilege in catalog order.",
		recv:       "p",
		values:     privileges,
		scopeCases: scopeCases,
	})

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format contract enums: %w", err)
	}
	return formatted, nil
}

type scopeMapping struct {
	privConst  string
	scopeConst string
}

type enumSpec struct {
	typeName   string
	typeDoc    string
	constDoc   string
	prefix     string
	allFunc    string
	allDoc     string
	recv       string
	values     []string
	scopeCases []scopeMapping
}

func writeEnum(b *bytes.Buffer, spec enumSpec) {
	writef(b, "// %s\n", spec.typeDoc)
	writef(b, "type %s string\n\n", spec.typeName)

	writef(b, "// %s\nconst (\n", spec.constDoc)
	for _, v := range spec.values {
		ident := goIdent(spec.prefix, v)
		writef(b, "\t// %s is the %q %s.\n", ident, v, spec.typeName)
		writef(b, "\t%s %s = %q\n", ident, spec.typeName, v)
	}
	b.WriteString(")\n\n")

	writef(b, "// String returns the canonical string representation of %s.\n", spec.recv)
	writef(b, "func (%s %s) String() string { return string(%s) }\n\n", spec.recv, spec.typeName, spec.recv)

	writef(b, "// Valid reports whether %s is a known %s value.\n", spec.recv, spec.typeName)
	writef(b, "func (%s %s) Valid() bool {\n\tswitch %s {\n\tcase ", spec.recv, spec.typeName, spec.recv)
	for i, v := range spec.values {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(goIdent(spec.prefix, v))
	}
	b.WriteString(":\n\t\treturn true\n\tdefault:\n\t\treturn false\n\t}\n}\n\n")

	if len(spec.scopeCases) > 0 {
		writef(b, "// Scope returns the execution Scope for %s, or an empty Scope when invalid.\n", spec.recv)
		writef(b, "func (%s %s) Scope() Scope {\n\tswitch %s {\n", spec.recv, spec.typeName, spec.recv)
		for _, m := range spec.scopeCases {
			writef(b, "\tcase %s:\n\t\treturn %s\n", m.privConst, m.scopeConst)
		}
		b.WriteString("\tdefault:\n\t\treturn \"\"\n\t}\n}\n\n")
	}

	writef(b, "// %s\n", spec.allDoc)
	writef(b, "func %s() []%s {\n\treturn []%s{\n", spec.allFunc, spec.typeName, spec.typeName)
	for _, v := range spec.values {
		writef(b, "\t\t%s,\n", goIdent(spec.prefix, v))
	}
	b.WriteString("\t}\n}\n\n")
}

// RenderCatalog renders internal/units/catalog/catalog_gen.go from a validated
// Catalog.
func RenderCatalog(cat Catalog) ([]byte, error) {
	conditions := collectConditions(cat)
	barriers := collectBarriers(cat)

	var b bytes.Buffer
	b.WriteString(generatedHeader)
	b.WriteString("\npackage catalog\n\n")
	b.WriteString("import \"github.com/sathyassn/agent-workstation-kit/internal/contract\"\n\n")

	if len(conditions) > 0 {
		b.WriteString("// Condition values generated from registry/units.toml.\nconst (\n")
		for _, c := range conditions {
			ident := goIdent("Condition", c)
			writef(&b, "\t// %s is the %q dependency condition.\n", ident, c)
			writef(&b, "\t%s Condition = %q\n", ident, c)
		}
		b.WriteString(")\n\n")
	}

	if len(barriers) > 0 {
		b.WriteString("// Barrier values generated from registry/units.toml.\nconst (\n")
		for _, br := range barriers {
			ident := goIdent("Barrier", br)
			writef(&b, "\t// %s is the %q synchronisation barrier.\n", ident, br)
			writef(&b, "\t%s Barrier = %q\n", ident, br)
		}
		b.WriteString(")\n\n")
	}

	b.WriteString("// Entries returns a fresh slice of every unit's catalog metadata in catalog order.\n")
	b.WriteString("func Entries() []Entry {\n\treturn []Entry{\n")
	for _, u := range cat.Units {
		writeEntryLiteral(&b, u)
	}
	b.WriteString("\t}\n}\n\n")

	b.WriteString("// Lookup returns the catalog Entry for id, or false when id is unknown.\n")
	b.WriteString("func Lookup(id contract.UnitID) (Entry, bool) {\n")
	b.WriteString("\tfor _, e := range Entries() {\n")
	b.WriteString("\t\tif e.ID == id {\n")
	b.WriteString("\t\t\treturn e, true\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t}\n")
	b.WriteString("\treturn Entry{}, false\n")
	b.WriteString("}\n")

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format catalog table: %w", err)
	}
	return formatted, nil
}

func writeEntryLiteral(b *bytes.Buffer, u UnitSpec) {
	b.WriteString("\t\t{\n")
	writef(b, "\t\t\tID: contract.%s,\n", goIdent("Unit", u.ID))
	writef(b, "\t\t\tDomain: contract.%s,\n", goIdent(typeDomain, u.Domain))
	b.WriteString("\t\t\tLinux: ")
	writePlatformMeta(b, u, osLinux)
	b.WriteString(",\n")
	b.WriteString("\t\t\tMacOS: ")
	writePlatformMeta(b, u, osMacOS)
	b.WriteString(",\n")
	if len(u.WaitsFor) > 0 {
		b.WriteString("\t\t\tWaitsFor: []Barrier{")
		for i, br := range u.WaitsFor {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(goIdent("Barrier", br))
		}
		b.WriteString("},\n")
	}
	writef(b, "\t\t\tEpic: %q,\n", u.Epic)
	writef(b, "\t\t\tMilestone: %q,\n", u.Milestone)
	b.WriteString("\t\t},\n")
}

func writePlatformMeta(b *bytes.Buffer, u UnitSpec, osName string) {
	st := u.Stage.forOS(osName)
	if st == unsetMarker || st == "" {
		b.WriteString("PlatformMeta{}")
		return
	}
	pr := u.Privilege.forOS(osName)
	sc := scopeForPrivilege(pr)

	b.WriteString("PlatformMeta{\n")
	b.WriteString("\t\t\t\tSupported: true,\n")
	writef(b, "\t\t\t\tStage: contract.%s,\n", goIdent(typeStage, st))
	writef(b, "\t\t\t\tPrivilege: contract.%s,\n", goIdent(typePrivilege, pr))
	writef(b, "\t\t\t\tScope: contract.%s,\n", goIdent(typeScope, sc))
	deps := u.Depends.forOS(osName)
	if len(deps) > 0 {
		b.WriteString("\t\t\t\tDepends: []contract.UnitID{")
		for i, d := range deps {
			if i > 0 {
				b.WriteString(", ")
			}
			writef(b, "contract.%s", goIdent("Unit", d))
		}
		b.WriteString("},\n")
	}
	condKeys := sortedMapKeys(u.DependsIf)
	var condEntries []string
	for _, cond := range condKeys {
		if len(u.DependsIf[cond].forOS(osName)) > 0 {
			condEntries = append(condEntries, cond)
		}
	}
	if len(condEntries) > 0 {
		b.WriteString("\t\t\t\tDependsIf: []ConditionalDep{\n")
		for _, cond := range condEntries {
			writef(b, "\t\t\t\t\t{Condition: %s, Units: []contract.UnitID{", goIdent("Condition", cond))
			for i, d := range u.DependsIf[cond].forOS(osName) {
				if i > 0 {
					b.WriteString(", ")
				}
				writef(b, "contract.%s", goIdent("Unit", d))
			}
			b.WriteString("}},\n")
		}
		b.WriteString("\t\t\t\t},\n")
	}
	b.WriteString("\t\t\t}")
}

func collectUnitIDs(cat Catalog) []string {
	out := make([]string, 0, len(cat.Units))
	for _, u := range cat.Units {
		out = append(out, u.ID)
	}
	return out
}

func collectStages(cat Catalog) []string {
	var out []string
	seen := make(map[string]bool)
	add := func(v string) {
		if v == "" || v == unsetMarker || seen[v] {
			return
		}
		seen[v] = true
		out = append(out, v)
	}
	for _, u := range cat.Units {
		add(u.Stage.Linux)
		add(u.Stage.MacOS)
	}
	return out
}

func collectScopes(cat Catalog) []string {
	var out []string
	seen := make(map[string]bool)
	add := func(p string) {
		sc := scopeForPrivilege(p)
		if sc == "" || seen[sc] {
			return
		}
		seen[sc] = true
		out = append(out, sc)
	}
	for _, u := range cat.Units {
		add(u.Privilege.Linux)
		add(u.Privilege.MacOS)
	}
	return out
}

func collectDomains(cat Catalog) []string {
	var out []string
	seen := make(map[string]bool)
	for _, u := range cat.Units {
		if u.Domain != "" && !seen[u.Domain] {
			seen[u.Domain] = true
			out = append(out, u.Domain)
		}
	}
	return out
}

func collectPrivileges(cat Catalog) []string {
	var out []string
	seen := make(map[string]bool)
	add := func(v string) {
		if v == "" || v == unsetMarker || seen[v] {
			return
		}
		seen[v] = true
		out = append(out, v)
	}
	for _, u := range cat.Units {
		add(u.Privilege.Linux)
		add(u.Privilege.MacOS)
	}
	return out
}

func collectConditions(cat Catalog) []string {
	seen := make(map[string]bool)
	for _, u := range cat.Units {
		for cond := range u.DependsIf {
			seen[cond] = true
		}
	}
	return sortedMapKeys(seen)
}

func collectBarriers(cat Catalog) []string {
	seen := make(map[string]bool)
	for _, u := range cat.Units {
		for _, br := range u.WaitsFor {
			seen[br] = true
		}
	}
	return sortedMapKeys(seen)
}

func goIdent(prefix, raw string) string {
	var b strings.Builder
	b.WriteString(prefix)
	for _, part := range strings.FieldsFunc(raw, func(r rune) bool {
		return r == '-' || r == '_' || r == ' '
	}) {
		b.WriteString(titleToken(part))
	}
	return b.String()
}

func titleToken(tok string) string {
	switch strings.ToLower(tok) {
	case unitSSH:
		return "SSH"
	case "vpn":
		return "VPN"
	case "mcp":
		return "MCP"
	case "id":
		return "ID"
	case "os":
		return "OS"
	case "cli":
		return "CLI"
	case "ui":
		return "UI"
	case "api":
		return "API"
	case "url":
		return "URL"
	case "dns":
		return "DNS"
	default:
		if tok == "" {
			return ""
		}
		return strings.ToUpper(tok[:1]) + strings.ToLower(tok[1:])
	}
}
