// RenderDocsTable renders the Markdown unit table embedded in documentation
// between the catalog:units markers.
func RenderDocsTable(cat Catalog) string {
	lines := make([]string, 0, len(cat.Units)+2)
	lines = append(lines,
		"| Unit | Domain | Linux stage | Linux runs as | macOS stage | macOS runs as | Depends on (Linux; macOS) | Epic | Milestone |",
		"|---|---|---|---|---|---|---|---|---|",
	)
	for _, u := range cat.Units {
		deps := docsDepsForOS(u, osLinux) + "; " + docsDepsForOS(u, osMacOS)
		if len(u.WaitsFor) > 0 {
			deps += "; waits for " + strings.Join(u.WaitsFor, ", ")
		}
		lines = append(lines, fmt.Sprintf(
			"| `%s` | %s | %s | %s | %s | %s | %s | %s | %s |",
			u.ID,
			u.Domain,
			docsCell(u.Stage.Linux),
			docsCell(u.Privilege.Linux),
			docsCell(u.Stage.MacOS),
			docsCell(u.Privilege.MacOS),
			deps,
			u.Epic,
			u.Milestone,
		))
	}
	return strings.Join(lines, "\n")
}

// ReplaceDocsTable replaces the table between the catalog:units markers in doc
// with table.
func ReplaceDocsTable(doc []byte, table string) ([]byte, error) {
	beginMarker := []byte(docsBeginMarker)
	endMarker := []byte(docsEndMarker)

	beginCount := bytes.Count(doc, beginMarker)
	if beginCount == 0 {
		return nil, errors.New("missing catalog:units:begin marker")
	}
	if beginCount > 1 {
		return nil, errors.New("duplicate catalog:units:begin marker")
	}
	endCount := bytes.Count(doc, endMarker)
	if endCount == 0 {
		return nil, errors.New("missing catalog:units:end marker")
	}
	if endCount > 1 {
		return nil, errors.New("duplicate catalog:units:end marker")
	}

	beginIdx := bytes.Index(doc, beginMarker)
	endIdx := bytes.Index(doc, endMarker)
	if endIdx < beginIdx {
		return nil, errors.New("catalog:units:end marker appears before catalog:units:begin marker")
	}
	start := beginIdx + len(beginMarker)
	end := endIdx

	var out bytes.Buffer
	out.Grow(start + len(table) + 2 + len(doc) - end)
	out.Write(doc[:start])
	out.WriteByte('\n')
	out.WriteString(table)
	out.WriteByte('\n')
	out.Write(doc[end:])
	return out.Bytes(), nil
}

func docsCell(value string) string {
	if value == "" || value == unsetMarker {
		return docsNoneCell
	}
	return value
}

func docsDepsForOS(u UnitSpec, osName string) string {
	items := slices.Clone(u.Depends.forOS(osName))
	for _, cond := range sortedMapKeys(u.DependsIf) {
		for _, dep := range u.DependsIf[cond].forOS(osName) {
			items = append(items, fmt.Sprintf("%s (if %s)", dep, cond))
		}
	}
	if len(items) == 0 {
		return docsNoneCell
	}
	return strings.Join(items, ", ")
}

func writef(b *bytes.Buffer, format string, args ...any) {
	b.Write(fmt.Appendf(nil, format, args...))
}

// RenderContractEnums renders internal/contract/enums_gen.go from a validated
// Catalog.
func RenderContractEnums(cat Catalog) ([]byte, error) {
	privileges := collectPrivileges(cat)
	scopeCases := make([]scopeMapping, 0, len(privileges))
	for _, p := range privileges {
		scopeCases = append(scopeCases, scopeMapping{
			privConst:  goIdent(typePrivilege, p),
			scopeConst: goIdent(typeScope, scopeForPrivilege(p)),
		})
	}
	valuesByType := map[string][]string{
		typeUnitID:    collectUnitIDs(cat),
		typeStage:     collectStages(cat),
		typeScope:     collectScopes(cat),
		typeDomain:    collectDomains(cat),
		typePrivilege: privileges,
	}

	var b bytes.Buffer
	b.WriteString(generatedHeader)
	b.WriteString("\npackage contract\n\n")

	for _, spec := range contractEnumDefs() {
		spec.values = valuesByType[spec.typeName]
		if spec.typeName == typePrivilege {
			spec.scopeCases = scopeCases
		}
		writeEnum(&b, spec)
	}

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format contract enums: %w", err)
	}
	return formatted, nil
}

type scopeMapping struct {
	privConst  string
	scopeConst string
}

type enumSpec struct {
	typeName   string
	typeDoc    string
	constDoc   string
	prefix     string
	allFunc    string
	allDoc     string
	recv       string
	values     []string
	scopeCases []scopeMapping
}

func writeEnum(b *bytes.Buffer, spec enumSpec) {
	writef(b, "// %s\n", spec.typeDoc)
	writef(b, "type %s string\n\n", spec.typeName)

	writef(b, "// %s\nconst (\n", spec.constDoc)
	for _, v := range spec.values {
		ident := goIdent(spec.prefix, v)
		writef(b, "\t// %s is the %q %s.\n", ident, v, spec.typeName)
		writef(b, "\t%s %s = %q\n", ident, spec.typeName, v)
	}
	b.WriteString(")\n\n")

	writef(b, "// String returns the canonical string representation of %s.\n", spec.recv)
	writef(b, "func (%s %s) String() string { return string(%s) }\n\n", spec.recv, spec.typeName, spec.recv)

	writef(b, "// Valid reports whether %s is a known %s value.\n", spec.recv, spec.typeName)
	writef(b, "func (%s %s) Valid() bool {\n\tswitch %s {\n\tcase ", spec.recv, spec.typeName, spec.recv)
	for i, v := range spec.values {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(goIdent(spec.prefix, v))
	}
	b.WriteString(":\n\t\treturn true\n\tdefault:\n\t\treturn false\n\t}\n}\n\n")

	if len(spec.scopeCases) > 0 {
		writef(b, "// Scope returns the execution Scope for %s, or an empty Scope when invalid.\n", spec.recv)
		writef(b, "func (%s %s) Scope() Scope {\n\tswitch %s {\n", spec.recv, spec.typeName, spec.recv)
		for _, m := range spec.scopeCases {
			writef(b, "\tcase %s:\n\t\treturn %s\n", m.privConst, m.scopeConst)
		}
		b.WriteString("\tdefault:\n\t\treturn \"\"\n\t}\n}\n\n")
	}

	writef(b, "// %s\n", spec.allDoc)
	writef(b, "func %s() []%s {\n\treturn []%s{\n", spec.allFunc, spec.typeName, spec.typeName)
	for _, v := range spec.values {
		writef(b, "\t\t%s,\n", goIdent(spec.prefix, v))
	}
	b.WriteString("\t}\n}\n\n")
}

// RenderCatalog renders internal/units/catalog/catalog_gen.go from a validated
// Catalog.
func RenderCatalog(cat Catalog) ([]byte, error) {
	conditions := collectConditions(cat)
	barriers := collectBarriers(cat)

	var b bytes.Buffer
	b.WriteString(generatedHeader)
	b.WriteString("\npackage catalog\n\n")
	b.WriteString("import \"github.com/sathyassn/agent-workstation-kit/internal/contract\"\n\n")

	if len(conditions) > 0 {
		writef(&b, "// %s values generated from registry/units.toml.\nconst (\n", catalogTypeCondition)
		for _, c := range conditions {
			ident := goIdent(catalogTypeCondition, c)
			writef(&b, "\t// %s is the %q dependency condition.\n", ident, c)
			writef(&b, "\t%s %s = %q\n", ident, catalogTypeCondition, c)
		}
		b.WriteString(")\n\n")
	}

	if len(barriers) > 0 {
		writef(&b, "// %s values generated from registry/units.toml.\nconst (\n", catalogTypeBarrier)
		for _, br := range barriers {
			ident := goIdent(catalogTypeBarrier, br)
			writef(&b, "\t// %s is the %q synchronisation barrier.\n", ident, br)
			writef(&b, "\t%s %s = %q\n", ident, catalogTypeBarrier, br)
		}
		b.WriteString(")\n\n")
	}

	writef(&b, "// %s returns a fresh slice of every unit's catalog metadata in catalog order.\n", catalogFuncEntries)
	writef(&b, "func %s() []%s {\n\treturn []%s{\n", catalogFuncEntries, catalogTypeEntry, catalogTypeEntry)
	for _, u := range cat.Units {
		writeEntryLiteral(&b, u)
	}
	b.WriteString("\t}\n}\n\n")

	writef(&b, "// %s returns the catalog %s for id, or false when id is unknown.\n", catalogFuncLookup, catalogTypeEntry)
	writef(&b, "func %s(id contract.%s) (%s, bool) {\n", catalogFuncLookup, typeUnitID, catalogTypeEntry)
	writef(&b, "\tfor _, e := range %s() {\n", catalogFuncEntries)
	b.WriteString("\t\tif e.ID == id {\n")
	b.WriteString("\t\t\treturn e, true\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t}\n")
	writef(&b, "\treturn %s{}, false\n", catalogTypeEntry)
	b.WriteString("}\n")

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format catalog table: %w", err)
	}
	return formatted, nil
}

func writeEntryLiteral(b *bytes.Buffer, u UnitSpec) {
	b.WriteString("\t\t{\n")
	writef(b, "\t\t\tID: contract.%s,\n", goIdent(prefixUnit, u.ID))
	writef(b, "\t\t\tDomain: contract.%s,\n", goIdent(typeDomain, u.Domain))
	b.WriteString("\t\t\tLinux: ")
	writePlatformMeta(b, u, osLinux)
	b.WriteString(",\n")
	b.WriteString("\t\t\tMacOS: ")
	writePlatformMeta(b, u, osMacOS)
	b.WriteString(",\n")
	if len(u.WaitsFor) > 0 {
		writef(b, "\t\t\tWaitsFor: []%s{", catalogTypeBarrier)
		for i, br := range u.WaitsFor {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(goIdent(catalogTypeBarrier, br))
		}
		b.WriteString("},\n")
	}
	writef(b, "\t\t\tEpic: %q,\n", u.Epic)
	writef(b, "\t\t\tMilestone: %q,\n", u.Milestone)
	b.WriteString("\t\t},\n")
}

func writePlatformMeta(b *bytes.Buffer, u UnitSpec, osName string) {
	st := u.Stage.forOS(osName)
	if st == unsetMarker || st == "" {
		writef(b, "%s{}", catalogTypePlatformMeta)
		return
	}
	pr := u.Privilege.forOS(osName)
	sc := scopeForPrivilege(pr)

	writef(b, "%s{\n", catalogTypePlatformMeta)
	b.WriteString("\t\t\t\tSupported: true,\n")
	writef(b, "\t\t\t\tStage: contract.%s,\n", goIdent(typeStage, st))
	writef(b, "\t\t\t\tPrivilege: contract.%s,\n", goIdent(typePrivilege, pr))
	writef(b, "\t\t\t\tScope: contract.%s,\n", goIdent(typeScope, sc))
	deps := u.Depends.forOS(osName)
	if len(deps) > 0 {
		writef(b, "\t\t\t\tDepends: []contract.%s{", typeUnitID)
		for i, d := range deps {
			if i > 0 {
				b.WriteString(", ")
			}
			writef(b, "contract.%s", goIdent(prefixUnit, d))
		}
		b.WriteString("},\n")
	}
	condKeys := sortedMapKeys(u.DependsIf)
	var condEntries []string
	for _, cond := range condKeys {
		if len(u.DependsIf[cond].forOS(osName)) > 0 {
			condEntries = append(condEntries, cond)
		}
	}
	if len(condEntries) > 0 {
		writef(b, "\t\t\t\tDependsIf: []%s{\n", catalogTypeConditionalDep)
		for _, cond := range condEntries {
			writef(b, "\t\t\t\t\t{Condition: %s, Units: []contract.%s{", goIdent(catalogTypeCondition, cond), typeUnitID)
			for i, d := range u.DependsIf[cond].forOS(osName) {
				if i > 0 {
					b.WriteString(", ")
				}
				writef(b, "contract.%s", goIdent(prefixUnit, d))
			}
			b.WriteString("}},\n")
		}
		b.WriteString("\t\t\t\t},\n")
	}
	b.WriteString("\t\t\t}")
}

func collectUnitIDs(cat Catalog) []string {
	out := make([]string, 0, len(cat.Units))
	for _, u := range cat.Units {
		out = append(out, u.ID)
	}
	return out
}

func collectStages(cat Catalog) []string {
	var out []string
	seen := make(map[string]bool)
	add := func(v string) {
		if v == "" || v == unsetMarker || seen[v] {
			return
		}
		seen[v] = true
		out = append(out, v)
	}
	for _, u := range cat.Units {
		add(u.Stage.Linux)
		add(u.Stage.MacOS)
	}
	return out
}

func collectScopes(cat Catalog) []string {
	var out []string
	seen := make(map[string]bool)
	add := func(p string) {
		sc := scopeForPrivilege(p)
		if sc == "" || seen[sc] {
			return
		}
		seen[sc] = true
		out = append(out, sc)
	}
	for _, u := range cat.Units {
		add(u.Privilege.Linux)
		add(u.Privilege.MacOS)
	}
	return out
}

func collectDomains(cat Catalog) []string {
	var out []string
	seen := make(map[string]bool)
	for _, u := range cat.Units {
		if u.Domain != "" && !seen[u.Domain] {
			seen[u.Domain] = true
			out = append(out, u.Domain)
		}
	}
	return out
}

func collectPrivileges(cat Catalog) []string {
	var out []string
	seen := make(map[string]bool)
	add := func(v string) {
		if v == "" || v == unsetMarker || seen[v] {
			return
		}
		seen[v] = true
		out = append(out, v)
	}
	for _, u := range cat.Units {
		add(u.Privilege.Linux)
		add(u.Privilege.MacOS)
	}
	return out
}

func collectConditions(cat Catalog) []string {
	seen := make(map[string]bool)
	for _, u := range cat.Units {
		for cond := range u.DependsIf {
			seen[cond] = true
		}
	}
	return sortedMapKeys(seen)
}

func collectBarriers(cat Catalog) []string {
	seen := make(map[string]bool)
	for _, u := range cat.Units {
		for _, br := range u.WaitsFor {
			seen[br] = true
		}
	}
	return sortedMapKeys(seen)
}

func goIdent(prefix, raw string) string {
	var b strings.Builder
	b.WriteString(prefix)
	for _, part := range strings.FieldsFunc(raw, func(r rune) bool {
		return r == '-' || r == '_' || r == ' '
	}) {
		b.WriteString(titleToken(part))
	}
	return b.String()
}

func titleToken(tok string) string {
	switch strings.ToLower(tok) {
	case unitSSH:
		return "SSH"
	case "vpn":
		return "VPN"
	case "mcp":
		return "MCP"
	case "id":
		return "ID"
	case "os":
		return "OS"
	case "cli":
		return "CLI"
	case "ui":
		return "UI"
	case "api":
		return "API"
	case "url":
		return "URL"
	case "dns":
		return "DNS"
	default:
		if tok == "" {
			return ""
		}
		return strings.ToUpper(tok[:1]) + strings.ToLower(tok[1:])
	}
}
